/**
 * Fallback for machines where Tailwind's native file scanner cannot load
 * (e.g. Windows Smart App Control / WDAC blocking unsigned .node binaries,
 * which forces the WASM scanner that finds no files).
 *
 * Extracts class-name candidates from src/ and writes them to
 * src/app/globals.css (between marker comments) as `@source inline(...)` —
 * it must live in the root stylesheet; Turbopack resolves @import separately. Unknown tokens are
 * ignored by Tailwind, so over-matching is harmless. Runs before dev/build.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "src");
const cssFile = path.join(srcDir, "app", "globals.css");
const START = "/* tailwind-safelist:start (generated by scripts/tailwind-safelist.mjs) */";
const END = "/* tailwind-safelist:end */";

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const full = path.join(dir, d.name);
    if (d.isDirectory()) return walk(full);
    return /\.(tsx?|jsx?|mdx?)$/.test(d.name) ? [full] : [];
  });
}

function balanced(t, open, close) {
  let depth = 0;
  for (const ch of t) {
    if (ch === open) depth++;
    else if (ch === close && --depth < 0) return false;
  }
  return depth === 0;
}

function isCandidate(t) {
  return (
    t.length > 1 &&
    t.length < 120 &&
    /^-?[a-z@[][\w\-:/.[\]()%#,&=*@>+~_!]*$/.test(t) &&
    !t.includes("/*") &&
    !t.includes("*/") &&
    balanced(t, "(", ")") &&
    balanced(t, "[", "]")
  );
}

const tokens = new Set();
for (const file of walk(srcDir)) {
  const text = fs.readFileSync(file, "utf8");
  for (const raw of text.split(/[\s"'`{}<>;]+/)) {
    const t = raw.replace(/^[(,]+|[),]+$/g, "");
    if (isCandidate(t)) tokens.add(t);
  }
}

const list = [...tokens].sort().join(" ");
const block = `${START}
@source inline(${JSON.stringify(list)});
${END}`;
const css = fs.readFileSync(cssFile, "utf8");
const i = css.indexOf(START);
const j = css.indexOf(END);
if (i === -1 || j === -1) throw new Error("tailwind-safelist markers not found in globals.css");
const next = css.slice(0, i) + block + css.slice(j + END.length);
if (next !== css) fs.writeFileSync(cssFile, next);
console.log(`[tailwind-safelist] ${tokens.size} candidates`);
